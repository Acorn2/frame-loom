import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {AudioManifestSchema} from '../src/schemas/audio-manifest.ts';
import {TtsConfigSchema} from '../src/schemas/tts-config.ts';
import {StoryboardSchema} from '../src/schemas/storyboard.ts';
import {hashNarration} from '../src/audio/text-hash.ts';
import {splitCaptionWindow} from '../src/audio/captions.ts';
import {getSceneTimeline} from '../src/timeline/scene-timeline.ts';
import {combineAudioSegments, probeAudioDuration, synthesizeSpeech} from './lib/tts-provider.mjs';
import {fingerprintFiles, fingerprintTtsConfig} from './lib/input-fingerprint.mjs';

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function writeJson(filePath, value) {
  fs.mkdirSync(path.dirname(filePath), {recursive: true});
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`);
}

function parseArgs(args) {
  const positional = [];
  const options = {force: false, reuse: false};
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === '--tts-config') {
      options.ttsConfigPath = args[index + 1];
      if (!options.ttsConfigPath) throw new Error('--tts-config 需要一个路径。');
      index += 1;
    } else if (arg === '--force') {
      options.force = true;
    } else if (arg === '--reuse') {
      options.reuse = true;
    } else {
      positional.push(arg);
    }
  }
  if (positional.length !== 1) {
    throw new Error('Usage: npm run synthesize:voiceover -- <project-dir> [--tts-config <tts-config.json>] [--reuse] [--force]');
  }
  options.projectPath = path.resolve(process.cwd(), positional[0]);
  return options;
}

function formatTimestamp(seconds) {
  const milliseconds = Math.max(0, Math.round(seconds * 1000));
  const hours = Math.floor(milliseconds / 3600000);
  const minutes = Math.floor((milliseconds % 3600000) / 60000);
  const remaining = milliseconds % 60000;
  const secs = Math.floor(remaining / 1000);
  const millis = remaining % 1000;
  return `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}:${String(secs).padStart(2, '0')},${String(millis).padStart(3, '0')}`;
}

function assertOutputAvailable(filePath, force) {
  if (fs.existsSync(filePath) && !force) {
    throw new Error(`输出文件已存在，未覆盖：${filePath}\n确认目标后使用 --force 显式覆盖。`);
  }
}

function isInside(directory, candidate) {
  const relative = path.relative(directory, candidate);
  return relative !== '' && relative !== '..' && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative);
}

function resolveOutputDirectory(projectPath, configuredPath) {
  const audioDirectory = path.join(projectPath, 'audio');
  const outputDirectory = path.resolve(projectPath, configuredPath);
  if (!isInside(audioDirectory, outputDirectory)) {
    throw new Error('TTS outputDirectory 必须位于项目的 audio/ 目录内。');
  }
  const realProject = fs.realpathSync(projectPath);
  const realAudio = fs.realpathSync(audioDirectory);
  if (!isInside(realProject, realAudio)) {
    throw new Error('项目的 audio/ 目录不能指向项目外。');
  }
  let existing = outputDirectory;
  while (true) {
    try {
      fs.lstatSync(existing);
      break;
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      existing = path.dirname(existing);
    }
  }
  const realOutput = path.resolve(fs.realpathSync(existing), path.relative(existing, outputDirectory));
  if (!isInside(realAudio, realOutput)) {
    throw new Error('TTS outputDirectory 不能通过符号链接指向 audio/ 目录外。');
  }
  return outputDirectory;
}

function createAudioConfig(projectPath, outputDirectory, format) {
  const audioDirectory = path.join(projectPath, 'audio');
  const generatedDirectory = path.relative(audioDirectory, outputDirectory);
  const extension = format === 'mp3' ? 'mp3' : 'wav';
  return {
    schemaVersion: '1.0',
    voiceover: {
      enabled: true,
      path: path.join(generatedDirectory, `voiceover.${extension}`),
      volume: 1,
      source: 'generated by configured TTS provider',
      license: 'configured provider; verify project usage rights'
    },
    captions: {
      enabled: true,
      path: path.join(generatedDirectory, 'captions.srt'),
      format: 'srt',
      source: 'generated from scene.narration and measured TTS segment timing'
    },
    sfx: []
  };
}

async function main(options) {
  const projectPath = options.projectPath;
  const storyboardPath = path.join(projectPath, 'storyboard.json');
  const defaultTtsConfigPath = path.join(projectPath, 'audio', 'tts-config.json');
  const ttsConfigPath = options.ttsConfigPath ? path.resolve(process.cwd(), options.ttsConfigPath) : defaultTtsConfigPath;
  if (!fs.existsSync(storyboardPath)) throw new Error(`缺少 storyboard.json：${storyboardPath}`);
  if (!fs.existsSync(ttsConfigPath)) throw new Error(`缺少 tts-config.json：${ttsConfigPath}`);

  const storyboardResult = StoryboardSchema.safeParse(readJson(storyboardPath));
  if (!storyboardResult.success) {
    throw new Error(`storyboard.json 无效：${storyboardResult.error.issues.map((item) => `${item.path.join('.')}: ${item.message}`).join('; ')}`);
  }
  const ttsResult = TtsConfigSchema.safeParse(readJson(ttsConfigPath));
  if (!ttsResult.success) {
    throw new Error(`tts-config.json 无效：${ttsResult.error.issues.map((item) => `${item.path.join('.')}: ${item.message}`).join('; ')}`);
  }
  const config = ttsResult.data;
  if (!config.enabled) throw new Error('tts-config.json 的 enabled 为 false，不能运行 TTS 合成。');

  const outputDirectory = resolveOutputDirectory(projectPath, config.outputDirectory);
  const extension = config.format === 'mp3' ? 'mp3' : 'wav';
  const fullAudioPath = path.join(outputDirectory, `voiceover.${extension}`);
  const captionsPath = path.join(outputDirectory, 'captions.srt');
  const audioConfigPath = path.join(projectPath, 'audio', 'audio-config.tts.json');
  const manifestPath = path.join(projectPath, 'audio', 'audio-manifest.json');
  const timeline = getSceneTimeline(storyboardResult.data);
  const configFingerprint = fingerprintTtsConfig(ttsConfigPath, projectPath);
  const narratedScenes = timeline.filter(({scene}) => scene.narration.trim());
  const segmentNames = narratedScenes.map(({scene}) => scene.id.toLowerCase());
  if (segmentNames.includes('voiceover')) throw new Error('scene id 不能是 voiceover：它与合成后的旁白文件名冲突。');
  if (new Set(segmentNames).size !== segmentNames.length) throw new Error('有旁白的 scene id 不能仅以大小写区分：它们会在部分文件系统中生成同名音频文件。');
  const segmentPaths = narratedScenes.map(({scene}) => path.join(outputDirectory, `${scene.id}.${extension}`));
  if (options.reuse && !options.force && fs.existsSync(manifestPath)) {
    const manifest = AudioManifestSchema.parse(readJson(manifestPath));
    const expected = narratedScenes;
    const sameTextAndTiming = manifest.segments.length === expected.length && manifest.segments.every((segment, index) => {
      const timing = expected[index];
      return timing && segment.sceneId === timing.scene.id && segment.textHash === hashNarration(timing.scene.narration.trim())
        && Math.abs(segment.startSec - timing.startFrame / storyboardResult.data.project.fps) < 0.001
        && Math.abs(segment.endSec - segment.startSec - segment.durationSec) < 0.001
        && segment.endSec <= timing.endFrame / storyboardResult.data.project.fps + 0.08;
    });
    if (manifest.ttsConfigFingerprint !== configFingerprint || manifest.projectDurationSec !== storyboardResult.data.project.durationFrames / storyboardResult.data.project.fps || !sameTextAndTiming || ![...segmentPaths, fullAudioPath, captionsPath, audioConfigPath].every((filePath) => fs.existsSync(filePath) && fs.statSync(filePath).size > 0) || manifest.artifactFingerprint !== fingerprintFiles([...segmentPaths, fullAudioPath, captionsPath], projectPath)) {
      throw new Error('已有 TTS 音频包与当前讲稿、时间轴或配置不一致；请核对后使用 --force 重新合成。');
    }
    console.log(`VOICEOVER REUSED ${path.relative(projectPath, audioConfigPath)}`);
    return {audioConfigPath, manifestPath, manifest};
  }
  for (const filePath of [...segmentPaths, fullAudioPath, captionsPath, audioConfigPath, manifestPath]) {
    assertOutputAvailable(filePath, options.force);
  }
  fs.mkdirSync(outputDirectory, {recursive: true});
  const stagingDirectory = fs.mkdtempSync(path.join(outputDirectory, '.synthesis-'));
  try {
    const fps = storyboardResult.data.project.fps;
    const projectDurationSec = storyboardResult.data.project.durationFrames / fps;
    const segments = [];
    for (const {scene, startFrame, endFrame} of timeline) {
      const text = scene.narration.trim();
      if (!text) continue;
      const startSec = startFrame / fps;
      const sceneEndSec = endFrame / fps;
      if (startSec < 0) throw new Error(`scene ${scene.id} 的时间轴起点为负数，无法生成旁白。`);
      const segmentPath = path.join(stagingDirectory, `${scene.id}.${extension}`);
      const finalSegmentPath = path.join(outputDirectory, `${scene.id}.${extension}`);
      console.log(`SYNTHESIZE ${scene.id} provider=${config.provider}`);
      await synthesizeSpeech({text, config, outputPath: segmentPath});
      const durationSec = probeAudioDuration(segmentPath);
      const endSec = startSec + durationSec;
      if (endSec > sceneEndSec + 0.08) {
        throw new Error(`scene ${scene.id} 的旁白时长 ${durationSec.toFixed(3)}s 超出 scene 可用时长 ${(sceneEndSec - startSec).toFixed(3)}s；请缩短 narration、延长 scene，或显式 retime。`);
      }
      if (endSec > projectDurationSec + 0.08) {
        throw new Error(`scene ${scene.id} 的旁白结束于 ${endSec.toFixed(3)}s，超出项目时长 ${projectDurationSec.toFixed(3)}s。`);
      }
      segments.push({
        sceneId: scene.id,
        text,
        textHash: hashNarration(text),
        absolutePath: segmentPath,
        path: path.relative(projectPath, finalSegmentPath),
        startSec,
        durationSec,
        endSec,
        source: 'tts'
      });
    }
    if (segments.length === 0) throw new Error('storyboard 没有可用于 TTS 的 scene.narration。');

    const stagedFullAudioPath = path.join(stagingDirectory, `voiceover.${extension}`);
    combineAudioSegments(segments, stagedFullAudioPath, projectDurationSec);
    const captions = segments.flatMap((segment) => splitCaptionWindow(segment.text, segment.startSec, segment.endSec)).map((cue, index) => [
      String(index + 1),
      `${formatTimestamp(cue.start)} --> ${formatTimestamp(cue.end)}`,
      cue.text,
      ''
    ].join('\n')).join('\n');
    const stagedCaptionsPath = path.join(stagingDirectory, 'captions.srt');
    fs.writeFileSync(stagedCaptionsPath, `${captions}\n`);

    const audioConfig = createAudioConfig(projectPath, outputDirectory, config.format);
    let manifest = AudioManifestSchema.parse({
      schemaVersion: '1.0',
      kind: 'voiceover',
      provider: config.provider,
      ttsConfigFingerprint: configFingerprint,
      generatedAt: new Date().toISOString(),
      storyboardPath: path.relative(projectPath, storyboardPath),
      textSource: 'scene.narration',
      segments: segments.map(({absolutePath: _absolutePath, ...segment}) => segment),
      fullAudioPath: path.relative(projectPath, fullAudioPath),
      captionsPath: path.relative(projectPath, captionsPath),
      audioConfigPath: path.relative(projectPath, audioConfigPath),
      projectDurationSec,
      notes: ['每个 scene 的旁白文本来自 scene.narration；音频 duration 来自 ffprobe 实测值。']
    });
    for (const segment of segments) {
      fs.renameSync(segment.absolutePath, path.resolve(projectPath, segment.path));
    }
    fs.renameSync(stagedFullAudioPath, fullAudioPath);
    fs.renameSync(stagedCaptionsPath, captionsPath);
    manifest = AudioManifestSchema.parse({...manifest, artifactFingerprint: fingerprintFiles([...segmentPaths, fullAudioPath, captionsPath], projectPath)});
    // The two JSON files are written last so an interrupted synthesis never
    // advertises an incomplete audio package as ready for rendering.
    writeJson(audioConfigPath, audioConfig);
    writeJson(manifestPath, manifest);
    console.log(`VOICEOVER READY ${path.relative(projectPath, audioConfigPath)}`);
    console.log(`MANIFEST READY ${path.relative(projectPath, manifestPath)}`);
    return {audioConfigPath, manifestPath, manifest};
  } finally {
    for (const name of fs.readdirSync(stagingDirectory)) fs.unlinkSync(path.join(stagingDirectory, name));
    fs.rmdirSync(stagingDirectory);
  }
}

const invokedPath = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : null;
if (invokedPath === import.meta.url) {
  try {
    await main(parseArgs(process.argv.slice(2)));
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
